#' Datasets providing building blocks for a location analysis
#'
#' Data used in the geomarketing chapter in Geocomputation with R.
#' See \url{https://r.geocompx.org/location.html} for details.
#'
#' \describe{
#'   \item{census_de}{A data.frame with German census data at 1km resolution.
#'     Contains columns: x, y (EPSG:3035 coordinates), pop (population count, 2022),
#'     women (percentage of women, 2011), mean_age (mean age in years, 2022),
#'     hh_size (average household size, 2022). Missing values are coded as -1.}
#'   \item{metro_names}{A data.frame with metropolitan area names derived from
#'     Census 2022 population data. Contains columns: city, town, state.
#'     Generated by aggregating 1km population grid to 20km resolution,
#'     filtering cells with >500,000 inhabitants, and reverse geocoding centroids.}
#'   \item{shops}{An sf data.frame of shop locations from OpenStreetMap
#'     for the identified metropolitan areas. Contains columns: osm_id, shop, geometry.}
#' }
#'
#' @format
#' \describe{
#'   \item{census_de}{A data.frame with census variables}
#'   \item{metro_names}{A data.frame with metropolitan area information}
#'   \item{shops}{An sf data.frame with POINT geometry}
#' }
#'
#' @aliases census_de metro_names shops
#' @examples
#' data("census_de", package = "spDataLarge")
#' head(census_de)
#'
#' data("metro_names", package = "spDataLarge")
#' metro_names
#'
#' data("shops", package = "spDataLarge")
#' head(shops)
